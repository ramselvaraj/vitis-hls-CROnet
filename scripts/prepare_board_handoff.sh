#!/usr/bin/env bash

set -euo pipefail

repo_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$repo_root"

out_base="${1:-build/board_handoff}"
stamp="${HANDOFF_STAMP:-$(date +%Y%m%d_%H%M%S)}"
handoff_dir="$out_base/cronet_vek280_hw_${stamp}"
package_dir="build/package.hw"
sd_dir="$package_dir/sd_card"
sd_img="$package_dir/sd_card.img"

require_file() {
    local path="$1"
    if [ ! -f "$path" ]; then
        echo "ERROR: missing required file: $path"
        echo "Build/repackage first, for example:"
        echo "  make BASE_PLATFORM=\"\$BASE_PLATFORM\" TARGET=hw vitis-package"
        exit 1
    fi
}

require_dir() {
    local path="$1"
    if [ ! -d "$path" ]; then
        echo "ERROR: missing required directory: $path"
        exit 1
    fi
}

copy_if_exists() {
    local src="$1"
    local dst_dir="$2"
    if [ -f "$src" ]; then
        mkdir -p "$dst_dir"
        cp -a "$src" "$dst_dir/"
    fi
}

copy_slim_vector_data() {
    local src_vectors="$sd_dir/data/cronet_hls_fp16_vectors"
    local dst_data="$handoff_dir/sd_card/data"
    local dst_vectors="$dst_data/cronet_hls_fp16_vectors"
    local case_count=0

    require_file "$src_vectors/manifest.json"

    rm -rf "$dst_data"
    mkdir -p "$dst_vectors/cases"
    cp -a "$src_vectors/manifest.json" "$dst_vectors/manifest.json"
    copy_if_exists "$sd_dir/data/README.md" "$dst_data"

    for case_dir in "$src_vectors"/cases/*; do
        [ -d "$case_dir" ] || continue

        local case_name
        case_name=$(basename "$case_dir")

        local branch_bin="$case_dir/inputs/fp16_words/branch_input.bin"
        local trunk_bin="$case_dir/inputs/fp16_words/trunk_input.bin"
        local golden_bin="$case_dir/golden/fp16_torch_f32/final_output.bin"

        if [ ! -f "$branch_bin" ] || [ ! -f "$trunk_bin" ] || [ ! -f "$golden_bin" ]; then
            echo "WARNING: skipping incomplete case '$case_name'"
            continue
        fi

        mkdir -p "$dst_vectors/cases/$case_name/inputs/fp16_words"
        mkdir -p "$dst_vectors/cases/$case_name/golden/fp16_torch_f32"
        cp -a "$branch_bin" "$dst_vectors/cases/$case_name/inputs/fp16_words/branch_input.bin"
        cp -a "$trunk_bin" "$dst_vectors/cases/$case_name/inputs/fp16_words/trunk_input.bin"
        cp -a "$golden_bin" "$dst_vectors/cases/$case_name/golden/fp16_torch_f32/final_output.bin"
        case_count=$((case_count + 1))
    done

    if [ "$case_count" -eq 0 ]; then
        echo "ERROR: no runnable cases found under $src_vectors/cases"
        exit 1
    fi

    echo "$case_count" > "$dst_vectors/BOARD_CASE_COUNT.txt"
}

require_file "$sd_img"
require_dir "$sd_dir"
require_file "$sd_dir/a.xclbin"
require_file "$sd_dir/host.exe"
require_file "$sd_dir/run_hw_board.sh"
require_file "$sd_dir/data/cronet_hls_fp16_vectors/manifest.json"

rm -rf "$handoff_dir"
mkdir -p "$handoff_dir/reports" "$handoff_dir/docs"

cp -a "$sd_img" "$handoff_dir/sd_card.img"
cp -a "$sd_dir" "$handoff_dir/sd_card"
chmod +x "$handoff_dir/sd_card/host.exe" "$handoff_dir/sd_card/run_hw_board.sh" 2>/dev/null || true
copy_slim_vector_data

copy_if_exists "build/cronet_kernel.hw.xo.compile_summary" "$handoff_dir/reports"
copy_if_exists "build/cronet_kernel.hw.xsa.link_summary" "$handoff_dir/reports"
copy_if_exists "build/v++.package_summary" "$handoff_dir/reports"
copy_if_exists "_x/reports/cronet_kernel.hw/hls_reports/cronet_kernel_csynth.rpt" "$handoff_dir/reports"
copy_if_exists "_x/reports/link/imp/impl_1_route_report_timing_summary_0.rpt" "$handoff_dir/reports"
copy_if_exists "_x/reports/link/imp/impl_1_kernel_util_routed.rpt" "$handoff_dir/reports"
copy_if_exists "_x/reports/link/imp/impl_1_full_util_routed.rpt" "$handoff_dir/reports"
copy_if_exists "docs/CRONet_HLS_Steps_4_6_AIE_Alignment.pdf" "$handoff_dir/docs"
copy_if_exists "docs/CRONet_HLS_HW_Utilization_Timing_Summary.md" "$handoff_dir/docs"

cat > "$handoff_dir/README_BOARD_RUN.md" <<'EOF'
# CRONet VEK280 Hardware Handoff

This folder contains a complete CRONet Vitis hardware package for the AMD
Versal VEK280 board.

## Contents

- `sd_card.img`: complete SD-card image generated by Vitis package.
- `sd_card/`: unpacked boot partition payload for inspection or manual copying.
- `sd_card/a.xclbin`: CRONet FPGA binary.
- `sd_card/host.exe`: AArch64 XRT host executable.
- `sd_card/run_hw_board.sh`: convenience runner for sanity/ramp/sparse/random cases.
- `sd_card/data/cronet_hls_fp16_vectors`: slim board data package containing
  only `manifest.json`, input FP16-word bins, and final-output golden bins.
- `reports/`: selected timing, utilization, HLS, compile, and link reports.

## Option A: Flash the SD-card image

On the workstation that has the SD card attached:

```bash
cd cronet_vek280_hw_*
lsblk
sudo umount /dev/sdX* 2>/dev/null || true
sudo dd if=sd_card.img of=/dev/sdX bs=64M status=progress conv=fsync
sync
```

Replace `/dev/sdX` with the actual SD-card device, not a partition such as
`/dev/sdX1`. Be careful: `dd` will overwrite the selected device.

Boot the VEK280 from the SD card.

## Option B: Copy payload onto an already-booted compatible image

If the board already runs a compatible VEK280 Linux/XRT image, copy the contents
of `sd_card/` to a directory on the board, then run from that directory.

The unpacked `sd_card/` folder in this handoff is intentionally slimmed for
board execution. It keeps only the files read by `host.exe`:

```text
data/cronet_hls_fp16_vectors/manifest.json
data/cronet_hls_fp16_vectors/cases/<case>/inputs/fp16_words/branch_input.bin
data/cronet_hls_fp16_vectors/cases/<case>/inputs/fp16_words/trunk_input.bin
data/cronet_hls_fp16_vectors/cases/<case>/golden/fp16_torch_f32/final_output.bin
```

## Run commands on the VEK280

After booting, find the mounted SD-card directory:

```bash
find /run/media /mnt -name run_hw_board.sh 2>/dev/null
```

Typical path:

```bash
cd /run/media/mmcblk0p1
```

Run one case with the default single inference:

```bash
chmod +x host.exe run_hw_board.sh 2>/dev/null || true
sh ./run_hw_board.sh sanity
```

Run one case for multiple timed inference iterations:

```bash
sh ./run_hw_board.sh sanity 2e-2 2e-2 100
```

The fourth argument is `n_iter`. The host prints total and average timing for
host-to-device sync, kernel execution, device-to-host sync, and the combined
input-to-output path.

Run all exported cases:

```bash
for case in sanity ramp sparse random; do
  echo "=== $case ==="
  sh ./run_hw_board.sh "$case"
done
```

## Expected successful ending

Each case should end with:

```text
CRONet XRT host
case: <case-name>
Launching cronet_kernel...
Kernel completed.
compare final_output: PASS ...
timing_iterations <n_iter>
timing_ms kernel_run         total ... avg ...
timing_ms inference_io       total ... avg ...
CRONET XRT TEST PASS
```

## Notes

- The implementation precision is PL/HLS IEEE FP16.
- The AIE paper reports BF16, so comparisons should be labeled
  `AIE BF16 vs PL/HLS FP16` unless both sides are rebuilt in the same datatype.
- Weights are compiled into the FPGA kernel. Runtime DDR is used only for branch
  input, trunk input, and final output.
EOF

{
    echo "CRONet VEK280 hardware handoff"
    echo "created: $(date -Iseconds)"
    echo "repo: $repo_root"
    if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        echo "git_commit: $(git rev-parse HEAD)"
        echo "git_branch: $(git rev-parse --abbrev-ref HEAD)"
        echo "git_status:"
        git status --short || true
    fi
    echo ""
    echo "package source:"
    echo "  $sd_img"
    echo "  $sd_dir"
} > "$handoff_dir/BUILD_INFO.txt"

find "$handoff_dir" -type f | sort > "$handoff_dir/FILE_LIST.txt"

(
    cd "$handoff_dir"
    {
        sha256sum sd_card.img
        sha256sum sd_card/a.xclbin
        sha256sum sd_card/host.exe
        sha256sum sd_card/run_hw_board.sh
        sha256sum sd_card/data/cronet_hls_fp16_vectors/manifest.json
        find sd_card/data/cronet_hls_fp16_vectors/cases -type f -name '*.bin' | sort | while read -r f; do
            sha256sum "$f"
        done
    } > SHA256SUMS.txt
)

if [ "${CREATE_TAR:-0}" = "1" ]; then
    tar_name="${handoff_dir}.tar.gz"
    tar -C "$out_base" -czf "$tar_name" "$(basename "$handoff_dir")"
    echo "Created archive: $tar_name"
fi

echo "Board handoff folder ready:"
echo "  $handoff_dir"
du -sh "$handoff_dir" 2>/dev/null || true
echo ""
echo "Give this folder to the board owner. Start with README_BOARD_RUN.md."
